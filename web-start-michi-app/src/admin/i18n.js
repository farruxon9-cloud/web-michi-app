export function makeT(lang) {
  const i = Math.max(0, ['ja', 'uz', 'en'].indexOf(lang));
  return (k) => (D[k] ? D[k][i] || D[k][2] : k);
}

export const I18nCtx = createContext({ t: makeT('ja'), lang: 'ja', setLang: () => {} });
export const useT = () => useContext(I18nCtx);
